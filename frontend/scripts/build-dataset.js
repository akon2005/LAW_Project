#!/usr/bin/env node
/**
 * Regenerates src/dataset.js from the project's sample dataset.
 *
 * Source : ../../VIDHIVEDA_Sample_Dataset.csv   (repo root)
 * Output : ../src/dataset.js
 *
 * Usage  : npm run build:dataset
 *
 * The CSV is the single source of truth for cases shown in the UI, so re-run
 * this whenever the dataset is updated instead of hand-editing dataset.js.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const CSV_PATH = resolve(HERE, '../../VIDHIVEDA_Sample_Dataset.csv');
const OUT_PATH = resolve(HERE, '../src/dataset.js');

/** Minimal RFC 4180 parser: handles quoted fields, escaped quotes and embedded newlines. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let inQuotes = false;

  for (let i = 0; i < text.length; i += 1) {
    const char = text[i];
    if (inQuotes) {
      if (char === '"') {
        if (text[i + 1] === '"') { field += '"'; i += 1; } else { inQuotes = false; }
      } else {
        field += char;
      }
    } else if (char === '"') {
      inQuotes = true;
    } else if (char === ',') {
      row.push(field); field = '';
    } else if (char === '\n') {
      row.push(field); rows.push(row); row = []; field = '';
    } else if (char !== '\r') {
      field += char;
    }
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const clean = (value) => (value || '').replace(/\s+/g, ' ').trim();

const table = parseCsv(readFileSync(CSV_PATH, 'utf8'));
const header = table[0].map((h) => clean(h).replace(/^\uFEFF/, ''));
const col = (name) => {
  const index = header.indexOf(name);
  if (index === -1) throw new Error(`Column not found in CSV: "${name}"`);
  return index;
};

const C = {
  no: col('S.No'),
  name: col('Case Name'),
  citation: col('Citation'),
  year: col('Year'),
  court: col('Court'),
  domain: col('Legal Domain'),
  sections: col('Applicable Section(s) / Article(s)'),
  principle: col('Key Legal Principle / Outcome'),
  source: col('Data Source'),
  recordType: col('Record Type'),
};

const records = table
  .slice(1)
  .filter((r) => clean(r[C.name]))
  .map((r) => {
    const serial = Number.parseInt(clean(r[C.no]), 10);
    const year = Number.parseInt(clean(r[C.year]), 10);
    return {
      id: `VD-${String(Number.isNaN(serial) ? 0 : serial).padStart(4, '0')}`,
      title: clean(r[C.name]),
      citation: clean(r[C.citation]),
      year: Number.isNaN(year) ? null : year,
      court: clean(r[C.court]),
      area: clean(r[C.domain]),
      sections: clean(r[C.sections]),
      summary: clean(r[C.principle]),
      source: clean(r[C.source]),
      recordType: clean(r[C.recordType]),
    };
  });

/** Sorted unique values, used to populate the filter dropdowns from real data. */
function options(values, fallback) {
  const unique = [...new Set(values.filter(Boolean))];
  return unique.length ? unique.sort((a, b) => a.localeCompare(b)) : [fallback];
}

const legalAreas = options(records.map((r) => r.area), 'General');
const courts = options(records.map((r) => r.court), 'Unknown court');
const years = [...new Set(records.map((r) => r.year).filter(Boolean))].sort((a, b) => b - a);
const recordTypes = options(records.map((r) => r.recordType), 'Unspecified');

const banner = `// @generated by scripts/build-dataset.js — do not edit by hand.
// Minified on purpose: this module is ~1,600 records and ships with the bundle.
// Source: VIDHIVEDA_Sample_Dataset.csv (${records.length} records).
// Regenerate with: npm run build:dataset
`;

const out = `${banner}
export const ALL_AREAS = 'All areas';
export const ALL_COURTS = 'All courts';
export const ANY_YEAR = 'Any year';

export const caseRecords = ${JSON.stringify(records)};

export const legalAreas = [ALL_AREAS, ...${JSON.stringify(legalAreas)}];

export const courts = [ALL_COURTS, ...${JSON.stringify(courts)}];

export const years = [ANY_YEAR, ...${JSON.stringify(years.map(String))}];

export const recordTypes = ${JSON.stringify(recordTypes)};

export const datasetStats = {
  total: ${records.length},
  areas: ${legalAreas.length},
  courts: ${courts.length},
  yearFrom: ${Math.min(...records.map((r) => r.year).filter(Boolean))},
  yearTo: ${Math.max(...records.map((r) => r.year).filter(Boolean))},
};
`;

mkdirSync(dirname(OUT_PATH), { recursive: true });
writeFileSync(OUT_PATH, out, 'utf8');

const kb = (Buffer.byteLength(out, 'utf8') / 1024).toFixed(0);
console.log(`Wrote ${OUT_PATH}`);
console.log(`  ${records.length} records · ${legalAreas.length} areas · ${courts.length} courts · ${kb} KB`);
